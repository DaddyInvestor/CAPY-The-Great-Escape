#!/usr/bin/env python3
"""Bundle the same production modules into a deterministic, one-paste Studio installer."""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MODULES = {
    "GameConfig": "src/ReplicatedStorage/Shared/GameConfig.luau",
    "WorldLayout": "src/ReplicatedStorage/Shared/WorldLayout.luau",
    "Geometry": "src/ServerScriptService/World/Geometry.luau",
    "Landscape": "src/ServerScriptService/World/Landscape.luau",
    "Landmarks": "src/ServerScriptService/World/Landmarks.luau",
    "ZooBuilder": "src/ServerScriptService/World/ZooBuilder.luau",
}
IMPORTS = {
    'require(Shared:WaitForChild("GameConfig"))': "__modules.GameConfig",
    'require(Shared:WaitForChild("WorldLayout"))': "__modules.WorldLayout",
    'require(script.Parent.Geometry)': "__modules.Geometry",
    'require(script.Parent.Landscape)': "__modules.Landscape",
    'require(script.Parent.Landmarks)': "__modules.Landmarks",
}


def generate():
    chunks = []
    digest = hashlib.sha256()
    for name, path in MODULES.items():
        text = (ROOT / path).read_text()
        digest.update(path.encode() + b"\0" + text.encode())
        for expression, replacement in IMPORTS.items():
            text = text.replace(expression, replacement)
        text = text.replace('local Shared = game:GetService("ReplicatedStorage"):WaitForChild("Shared")\n', '')
        if re.search(r'\brequire\s*\(|\bscript\.', text):
            raise ValueError(f"Unbundled dependency in {path}")
        chunks.append(f'-- Source: {path}\n__modules.{name} = (function()\n{text}\nend)()\n')
    return ('--!strict\n-- GENERATED by python3 tools/generate_installer.py; do not edit by hand.\n'
            '-- Paste this ENTIRE file into the Roblox Studio Command Bar in EDIT MODE.\n'
            '-- No Rojo, HTTP, external assets, packages or Play Mode are required.\n'
            '-- Only an owned CapyWorld is replaced; unrelated content is preserved.\n'
            f'-- Modular source SHA256: {digest.hexdigest()}\n'
            'local __modules: {[string]: any} = {}\n\n' + '\n'.join(chunks)
            + '\nlocal world = __modules.ZooBuilder.Build()\n'
            + 'print("[CAPY-M01A-R1] Installed in Workspace:", world:GetFullName())\n'
            + 'print("Save the place. R1 layout only; Studio Playtest status is NOT RUN by this installer.")\n')


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the checked-in installer is stale")
    args = parser.parse_args()
    output = ROOT / "studio/InstallZoo.command.luau"
    expected = generate()
    if args.check:
        if not output.exists() or output.read_text() != expected:
            raise SystemExit("Installer is stale: run python3 tools/generate_installer.py")
        print("PASS: one-paste installer matches modular source")
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(expected)
        print(f"Generated {output.relative_to(ROOT)} ({len(expected.encode())} bytes)")
