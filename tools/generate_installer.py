#!/usr/bin/env python3
"""Bundle the same production modules into a deterministic, one-paste Studio installer."""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MODULES = {
    "GameConfig": "src/ReplicatedStorage/Shared/GameConfig.luau",
    "QuestConfig": "src/ReplicatedStorage/Shared/QuestConfig.luau",
    "WorldLayout": "src/ReplicatedStorage/Shared/WorldLayout.luau",
    "Geometry": "src/ServerScriptService/World/Geometry.luau",
    "Landscape": "src/ServerScriptService/World/Landscape.luau",
    "Landmarks": "src/ServerScriptService/World/Landmarks.luau",
    "StoryDetails": "src/ServerScriptService/World/StoryDetails.luau",
    "ZooBuilder": "src/ServerScriptService/World/ZooBuilder.luau",
}
IMPORTS = {
    'require(Shared:WaitForChild("QuestConfig"))': "__modules.QuestConfig",
    'require(script.Parent.StoryDetails)': "__modules.StoryDetails",
    'require(script.Parent.QuestLogic)': "__modules.QuestLogic",
    'require(Shared:WaitForChild("GameConfig"))': "__modules.GameConfig",
    'require(Shared:WaitForChild("WorldLayout"))': "__modules.WorldLayout",
    'require(script.Parent.Geometry)': "__modules.Geometry",
    'require(script.Parent.Landscape)': "__modules.Landscape",
    'require(script.Parent.Landmarks)': "__modules.Landmarks",
}


def bundle_runtime():
    chunks = ["local __modules = {}"]
    for name,path in {
        "QuestConfig":"src/ReplicatedStorage/Shared/QuestConfig.luau",
        "QuestLogic":"src/ServerScriptService/Gameplay/QuestLogic.luau",
        "QuestServer":"src/ServerScriptService/Gameplay/QuestServer.luau",
    }.items():
        text=(ROOT/path).read_text()
        for expression,replacement in IMPORTS.items(): text=text.replace(expression,replacement)
        text=text.replace('local Shared = game:GetService("ReplicatedStorage"):WaitForChild("Shared")\n','')
        if re.search(r'\brequire\s*\(',text): raise ValueError(f"Unbundled runtime import: {path}")
        chunks.append(f"__modules.{name} = (function()\n{text}\nend)()")
    chunks.append("__modules.QuestServer.Start(script.Parent.Parent)")
    return "\n".join(chunks)


def literal(text):
    assert "]====]" not in text
    return "[====["+text+"]====]"


def generate():
    chunks = []
    digest = hashlib.sha256()
    runtime_source = bundle_runtime()
    client_source = (ROOT/"src/StarterPlayer/StarterPlayerScripts/CapyClient.client.luau").read_text()
    digest.update(b"runtime\0" + runtime_source.encode() + b"client\0" + client_source.encode())
    for name, path in MODULES.items():
        text = (ROOT / path).read_text()
        digest.update(path.encode() + b"\0" + text.encode())
        for expression, replacement in IMPORTS.items():
            text = text.replace(expression, replacement)
        text = text.replace('local Shared = game:GetService("ReplicatedStorage"):WaitForChild("Shared")\n', '')
        if re.search(r'\brequire\s*\(|\bscript\.', text):
            raise ValueError(f"Unbundled dependency in {path}")
        chunks.append(f'-- Source: {path}\n__modules.{name} = (function()\n{text}\nend)()\n')
    return ('--!strict\n-- GENERATED by python3 tools/generate_installer.py; do not edit by hand.\n'
            '-- Paste this ENTIRE file into the Roblox Studio Command Bar in EDIT MODE.\n'
            '-- No Rojo, HTTP, external assets or packages. Install in Edit Mode; Play starts the quest.\n'
            '-- Only an owned CapyWorld is replaced; unrelated content is preserved.\n'
            f'-- Modular source SHA256: {digest.hexdigest()}\n'
            'local __modules: {[string]: any} = {}\n\n' + '\n'.join(chunks)
            + '\nlocal function prepareRuntime(world)\n'
            + 'local runtime = Instance.new("Folder")\nruntime.Name = "Runtime"\nruntime.Parent = world\n'
            + 'local template = Instance.new("ScreenGui")\ntemplate.Name = "ClientTemplate"\n'
            + 'template:SetAttribute("GeneratorId","CAPY-M01A")\ntemplate.ResetOnSpawn = false\ntemplate.Parent = runtime\n'
            + 'local client = Instance.new("LocalScript")\nclient.Name = "CapyClient"\nclient.Source = '
            + literal(client_source) + '\nclient.Parent = template\n'
            + 'local server = Instance.new("Script")\nserver.Name = "CapyServer"\nserver.Source = '
            + literal(runtime_source) + '\nserver.Parent = runtime\nend\nlocal world = __modules.ZooBuilder.Build(prepareRuntime)\n'
            + 'print("[CAPY POLISH] Installed in Workspace:", world:GetFullName())\n'
            + 'print("Save the place, then Play for Mango\'s Morning Rescue. Studio Playtest has NOT RUN here.")\n')


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the checked-in installer is stale")
    args = parser.parse_args()
    output = ROOT / "STUDIO_ONE_PASTE.lua"
    expected = generate()
    if args.check:
        if not output.exists() or output.read_text() != expected:
            raise SystemExit("Installer is stale: run python3 tools/generate_installer.py")
        print("PASS: one-paste installer matches modular source")
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(expected)
        print(f"Generated {output.relative_to(ROOT)} ({len(expected.encode())} bytes)")
